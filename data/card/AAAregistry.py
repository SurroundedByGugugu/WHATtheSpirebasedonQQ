def create_card(card_id):
    create_func = CARD_REGISTRY.get(card_id)

    if create_func is None:
        raise ValueError("未知卡牌 ID：{}".format(card_id))

    return create_func()


def create_deck(card_ids):
    return [create_card(card_id) for card_id in card_ids]